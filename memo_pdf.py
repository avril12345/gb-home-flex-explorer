"""One-page PDF memo of the country scorecard (fpdf2)."""
from __future__ import annotations

import os
from datetime import date

from fpdf import FPDF, FontFace

from scorecard import COUNTRIES, METRICS, SOURCES

_FONT_CANDIDATES = [
    ("C:/Windows/Fonts/arial.ttf", "C:/Windows/Fonts/arialbd.ttf"),
    ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"),
    ("/Library/Fonts/Arial.ttf", "/Library/Fonts/Arial Bold.ttf"),
]

_ASCII = {"≈": "~", "—": "-", "–": "-", "’": "'", "‘": "'", "“": '"', "”": '"', "≥": ">=", "…": "...", "→": "->"}


def _setup_font(pdf: FPDF) -> tuple[str, bool]:
    for reg, bold in _FONT_CANDIDATES:
        if os.path.exists(reg) and os.path.exists(bold):
            pdf.add_font("Body", "", reg)
            pdf.add_font("Body", "B", bold)
            return "Body", True
    return "Helvetica", False


def _clean(s: str, unicode_ok: bool) -> str:
    if unicode_ok:
        return s
    for k, v in _ASCII.items():
        s = s.replace(k, v)
    return s.encode("latin-1", "replace").decode("latin-1")


def _render(sc: dict, fs: float, author_line: str) -> FPDF:
    pdf = FPDF(orientation="L", unit="mm", format="A4")
    pdf.set_auto_page_break(auto=True, margin=8)
    pdf.set_margins(10, 9, 10)
    font, uni = _setup_font(pdf)
    c = lambda s: _clean(s, uni)  # noqa: E731
    pdf.add_page()

    # Header
    pdf.set_font(font, "B", fs + 5)
    pdf.cell(0, fs * 0.75, c("MEMO — Household flexibility readiness: NL, DE, FR, IE, ES"), new_x="LMARGIN", new_y="NEXT", align="L")
    pdf.set_font(font, "", fs)
    pdf.set_text_color(90, 90, 90)
    pdf.cell(0, fs * 0.5, c(f"{author_line}Date: {date.today():%d %B %Y}  ·  Generated by Home energy-saving explorer"),
             new_x="LMARGIN", new_y="NEXT", align="L")
    pdf.set_text_color(0, 0, 0)
    pdf.ln(1)
    pdf.set_font(font, "", fs)
    pdf.multi_cell(
        0, fs * 0.45,
        c("Purpose: compare the installed base of flexible household assets and the market routes that let households "
          "monetise flexibility. Figures are the latest sourced values found (data year shown); blank cells mean no "
          "sourced figure was found — they are not zero. Source keys in [brackets] are listed below."),
        new_x="LMARGIN", new_y="NEXT",
    )
    pdf.ln(1)

    # Table
    pdf.set_font(font, "", fs)
    col_w = (22, 38, 28, 52, 33, 104)
    headings = ["Country", "EV stock (BEV+PHEV cars)", "Heat pump stock", "Home battery stock",
                "Smart meter rollout", "Household access to flexibility / balancing markets"]
    with pdf.table(col_widths=col_w, text_align="LEFT", line_height=fs * 0.42, padding=0.8,
                   headings_style=FontFace(emphasis="BOLD", fill_color=(232, 238, 247)),
                   first_row_as_headings=True) as t:
        row = t.row()
        for h in headings:
            row.cell(c(h))
        for ctry in COUNTRIES:
            r = t.row()
            r.cell(c(ctry))
            for m in METRICS:
                cell = sc[ctry][m]
                srcs = " [" + ", ".join(cell["sources"]) + "]" if cell["sources"] else ""
                if m == METRICS[4]:
                    txt = f"{cell['display']}: {cell['note']}{srcs}"
                elif cell["display"]:
                    txt = f"{cell['display']} ({cell['year']}){srcs}"
                else:
                    txt = f"— Blank: {cell['note']}{srcs}"
                r.cell(c(txt))
    pdf.ln(1.5)

    # Notes
    pdf.set_font(font, "B", fs)
    pdf.cell(0, fs * 0.45, "Notes", new_x="LMARGIN", new_y="NEXT", align="L")
    pdf.set_font(font, "", fs - 0.5)
    notes = [
        "EV: ACEA publishes fleet shares rounded to 0.1 pp; counts are derived (share × 2024 car fleet). "
        "Germany's KBA counted 2,034,260 BEVs alone at 1 Jan 2026.",
        "Heat pumps: EHPA stock includes reversible air-to-air units, which raises France and Spain relative to heating-only counts.",
        "Smart meters: national figures from smartEn (2025) / ESB Networks; ACER-CEER 2024 bands corroborate (DE 0–10%, others 80–100%).",
        "Access ratings (Yes / Partial / Limited) are this memo's summary of the cited regulatory assessments, not an official score.",
    ]
    for n in notes:
        pdf.multi_cell(0, fs * 0.42, c("• " + n), new_x="LMARGIN", new_y="NEXT", align="L")
    pdf.ln(1)
    pdf.set_font(font, "B", fs)
    pdf.cell(0, fs * 0.45, "Sources", new_x="LMARGIN", new_y="NEXT", align="L")
    pdf.set_font(font, "", fs - 1)
    used = sorted({s for ctry in COUNTRIES for m in METRICS for s in sc[ctry][m]["sources"]})
    for k in used:
        name, url = SOURCES[k]
        pdf.multi_cell(0, fs * 0.38, c(f"[{k}] {name}. {url}"), new_x="LMARGIN", new_y="NEXT", align="L")
    return pdf


def build_memo(sc: dict, author: str = "") -> bytes:
    author_line = f"From: {author}  ·  " if author else ""
    fs = 8.0
    while fs >= 5.0:
        pdf = _render(sc, fs, author_line)
        if pdf.pages_count == 1:
            return bytes(pdf.output())
        fs -= 0.25
    raise RuntimeError("Scorecard memo could not be fitted on one page.")
